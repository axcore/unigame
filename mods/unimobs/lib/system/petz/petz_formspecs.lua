function unimobs.petz_api.create_standard_mob_form(pname)

    -- Original to unimobs, replacing the confusing forms from the original petz modpack
    -- Called by unimobs.petz_api.on_rightclick_callback() when the player right-clicks a tamed mob,
    --      and no other action has been taken as a result
    -- Creates the main mob formspec

    -- Basic initialisation
    local mob = unimobs.petz_global.formspec_player_table[pname]
    if not mob then
        return ""
    end

    local creative_flag = unilib.utils.is_creative(pname)

    -- Because mobs that are repelled by certain items are relatively row, don't bother showing that
    --      row in the formspec if there's nothing to show (in contrast, even if the mob doesn't
    --      follow certain items, still show that row)
    local show_repel_flag = false
    if unimobs.petz_api.get_msetting(mob.mob_type, "repel_item_first") ~= "" then
        show_repel_flag = true
    end

    -- Get the number of rows to be displayed in the middle section
    local left_row_count, right_row_count = get_row_counts(mob, show_repel_flag)
    -- Get the number of order/action buttons to be displayed in the bottom section (not including
    --      any extension buttons)
    local order_btn_count, action_btn_count = get_ordinary_button_counts(mob)
    -- Get lists of extension buttons, to be passed on to the sub-functions
    local order_ext_btn_list, action_ext_btn_list = get_lists_of_extension_buttons(mob)

    -- Calculate the actual height of the formspec
    local row_height = 0.75

    order_btn_count = order_btn_count + #order_ext_btn_list
    action_btn_count = action_btn_count + #action_ext_btn_list

    local formspec_height, middle_height
    if left_row_count > right_row_count then
        middle_height = (left_row_count * row_height)
    else
        middle_height = (right_row_count * row_height)
    end

    formspec_height = formspec_min_height + middle_height

    if order_btn_count > 0 and action_btn_count > 0 then
        formspec_height = formspec_height + 2.4
    elseif order_btn_count > 0 or action_btn_count > 0 then
        formspec_height = formspec_height + 1.4
    end

    -- Create the formspec
    local header_height = 1.5
    local left_column = 0.75
    local right_column = 5

    local formspec = "size[" .. formspec_width .. "," .. formspec_height .. "]"

    -- Header
    formspec = formspec .. get_header_str(pname, mob, middle_height)

    -- Middle section, left side: main characteristics
    local left_y = header_height

    if mob.owner and (mob.for_sale_flag or not core.is_singleplayer()) then

        formspec = formspec .. get_owner_str(mob, left_column, left_y)
        left_y = left_y + row_height

    end

    formspec = formspec .. get_mob_type_str(mob, left_column, left_y, (right_column - left_column))
    left_y = left_y + row_height

    formspec = formspec .. get_mob_skin_str(mob, left_column, left_y)
    left_y = left_y + row_height

    if unimobs.petz_setting.show_formspec_items_flag then

        if show_repel_flag then

            formspec = formspec .. get_repel_str(pname, mob, left_column, left_y, creative_flag)
            left_y = left_y + row_height

        end

        formspec = formspec .. get_follow_str(pname, mob, left_column, left_y, creative_flag)
        left_y = left_y + row_height

        formspec = formspec .. get_feed_str(pname, mob, left_column, left_y, creative_flag)
        left_y = left_y + row_height

        formspec = formspec .. get_breed_str(pname, mob, left_column, left_y, creative_flag)
        left_y = left_y + row_height

        if mob.capture_type == "lasso" or
                mob.capture_type == "animal_net" or
                mob.capture_type == "bug_net" then

            formspec = formspec .. get_capture_str(pname, mob, left_column, left_y, creative_flag)
            left_y = left_y + row_height

        end

    end

    -- Middle section, left side: variable characteristics
    local right_y = header_height

    formspec = formspec .. get_health_str(mob, right_column, right_y)
    right_y = right_y + row_height

    formspec = formspec .. get_mating_str(mob, right_column, right_y)
    right_y = right_y + row_height

    formspec = formspec .. get_generation_str(mob, right_column, right_y)
    right_y = right_y + row_height

    formspec = formspec .. get_genetics_str(mob, right_column, right_y)
    right_y = right_y + row_height

    if unimobs.petz_setting.enable_tamagotchi_mode_flag and mob.has_tamagotchi_mode_flag then

        formspec = formspec .. get_tamagotchi_hunger_str(mob, right_column, right_y)
        right_y = right_y + row_height

        formspec = formspec .. get_tamagotchi_groom_str(mob, right_column, right_y)
        right_y = right_y + row_height

    end

    if mob.has_dreamcatcher_flag and mob.back_home_pos then

        formspec = formspec .. get_home_str(mob, right_column, right_y)
        right_y = right_y + row_height

    end

    -- Bottom section: button strips
    local bottom_y
    if left_y > right_y then
        bottom_y = left_y + 0.5
    else
        bottom_y = right_y + 0.5
    end

    if order_btn_count > 0 then

        formspec = formspec .. get_order_btn_str(
            mob, 0.5, bottom_y, (formspec_width - 1), order_btn_count, order_ext_btn_list
        )
        bottom_y = bottom_y + 1

    end

    if action_btn_count > 0 then

        formspec = formspec .. get_action_btn_str(
            mob, 0.5, bottom_y, (formspec_width - 1), action_btn_count, action_ext_btn_list
        )
        bottom_y = bottom_y + 1

    end

    return formspec

end

