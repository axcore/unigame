function unimobs.petz_api.register_formspec_extension(mob_type, data_table)

    -- Original to unimobs
    -- Called by any package which wants to add additional buttons to the main mob formspec

    extension_count = extension_count + 1

    local mini_table = {
        id = extension_count,
        order_flag = data_table.order_flag or false,
        click_func = data_table.click_func or nil,
        draw_func = data_table.draw_func or nil,
    }

    if extension_table[mob_type] == nil then
        extension_table[mob_type] = { mini_table }
    else
        table.insert(extension_table[mob_type], mini_table)
    end

end

