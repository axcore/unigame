-- Local functions - make/cancel announcements
---------------------------------------------------------------------------------------------------

local function compose_node_announcement(
    pname, formspec_portion, node_description, full_name, item_type
)
    -- Update local data
    identify_status_table[pname]["pointed_thing"] = full_name

    -- Show the original package name, rather than the parent mod name, if required
    local bottom_colour
    local parent_name = unilib.utils.get_mod_name(full_name)

    if unilib.setting.identify_package_name_flag and
            parent_name == unilib.core.name and
            unilib.global.node_parent_table[full_name] ~= nil then

        parent_name = unilib.global.node_parent_table[full_name]
        -- (Switch to yellow text)
        bottom_colour = colour_yellow

    else

        -- (Restore original red text)
        bottom_colour = colour_red

    end

    local img_scale
    if item_type == "node" then
        img_scale = img_scale_node
    else
        img_scale = img_scale_craftitem
    end

    -- Compose the announcement
    return {
        category = "identify",
        img = formspec_portion,
        img_scale = img_scale,
        text_top = node_description,
        text_top_colour = colour_white,
        text_bottom = parent_name,
        text_bottom_colour = bottom_colour,
    }

end

local function compose_unknown_node_announcement(pname, full_name)

    -- Update local data
    identify_status_table[pname]["pointed_thing"] = "unknown"

    -- Make the announcement
    return {
        category = "identify",
        img = generate_inventorycube("unknown_node.png", "unknown_node.png", "unknown_node.png"),
        img_scale = img_scale_node,
        -- (N.B. Currently can't translate this string, as it messes up the width)
        text_top = "Unknown item",
        text_top_colour = colour_white,
        text_bottom = unilib.utils.get_mod_name(full_name),
        text_bottom_colour = colour_red,
    }

end

local function do_announcement(pname, full_name)

    -- List of three items, in the form
    --      - A formspec portion with a single inventorycube[] element (or "ignore on failure")
    --      - The string "node" or "craftitem"
    --      - The item's definition table on success (or "false" on failure)
    local formspec_portion, item_type, def_table = generate_node_data(full_name)

    if not def_table then

        unilib.announce.add_short_announcement(
            pname,
            compose_unknown_node_announcement(pname, full_name)
        )

    else

        local description = def_table.description
        if description == nil or description == "" then
        
            -- (N.B. Currently can't translate this string, as it messes up the width)
            description = "Unknown item"

        end
        
        unilib.announce.add_short_announcement(
            pname,
            compose_node_announcement(
                pname,
                formspec_portion,
                description,
                full_name,
                item_type
            )
        )

    end

end

local function cancel_announcement(pname)

    -- Update local data
    identify_status_table[pname]["pointed_thing"] = "ignore"

    -- Cancel the announcement generated by the code above, if it's visible
    unilib.announce.remove_short_announcement(pname, "identify")

end

---------------------------------------------------------------------------------------------------
-- Local functions - main loops
---------------------------------------------------------------------------------------------------

local function monitor_announcements(pname)

    -- Check whether a "long" announcement for the specified player has just been removed, meaning
    --      that code in this file can send an identify announcement, even if the player is not
    --      pointing at something new

    local visible_flag = unilib.announce.is_long_announcement_visible(pname)
    if not visible_flag and long_announce_table[pname] == true then

        long_announce_table[pname] = nil
        resume_identify_table[pname] = true

    else

        if visible_flag and long_announce_table[pname] == nil then
            long_announce_table[pname] = true
        end

        resume_identify_table[pname] = nil

    end

end

local function do_simple_loop()

    -- N.B. Not in original code - there is no reason why this loop needs to run more often than
    --      10 times a second
    local timer = 0
    local timer_tick = 0.1

    -- Non-optimised code, from "what_is_this_uwu" mod
    core.register_globalstep(function(dtime)

        timer = timer + dtime
        if timer > timer_tick then

            timer = 0

            for pname, data_table in pairs(identify_status_table) do

                monitor_announcements(pname)

                local node
                if data_table.enabled_flag then
                    node = unilib.utils.get_pointed_node(core.get_player_by_name(pname))
                end

                if node then

                    local full_name = node.name
                    if data_table.pointed_thing ~= full_name or
                            resume_identify_table[pname] == true then

                        -- New thing to identify; update the HUD
                        do_announcement(pname, full_name)

                    end

                else

                    -- Not pointed at anything; cancel the HUD, if visible
                    cancel_announcement(pname)

                end

            end

        end

    end)

end

local function do_optimised_loop()

    -- Code optimised for servers, from "what_is_this_owo" mod
    core.register_on_punchnode(function(pos, node, player, pointed_thing)

        local pname = core.get_player_name(player)
        local data_table = identify_status_table[pname]

        monitor_announcements(pname)

        if data_table.enabled_flag then

            local full_name = node.name
            if data_table.pointed_thing ~= full_name or
                    resume_identify_table[pname] == true then

                -- New pointed thing; update the HUD
                do_announcement(pname, full_name)

            else

                -- Not pointed at anything; cancel the HUD, if visible
                cancel_announcement(pname)

            end

        end

    end)

end

