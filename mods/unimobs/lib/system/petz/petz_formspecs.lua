core.register_on_player_receive_fields(function(player, formname, fields)

    -- Callback for the formspec created by unimobs.petz_api.create_standard_mob_form()
    -- Adadpted from corresponding callback in original code

    if formname ~= "unilib:form_unimobs_standard_mob" then
        return false
    end

    local reopen_formspec_flag = false

    local pname = player:get_player_name()
    local mob = unimobs.petz_global.formspec_player_table[pname]
    if mob and mob.object and not mob.is_dead_flag then

        -- Order buttons (not visible, if the required packages have not been loaded)
        if fields.btn_order_follow then

            unilib.pkg.mtb_order_follow.do_action(mob, player)
            -- N.B. Unlike the original code, all order buttons generate a sound effect as an
            --      acknowledgement
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

        elseif fields.btn_order_stand_here then

            unilib.pkg.mtb_order_stand_here.do_action(mob)
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

        elseif fields.btn_order_guard then

            unilib.pkg.mtb_order_guard.do_action(mob)
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

        elseif fields.btn_order_autonomy then

            unimobs.mobkit_api.clear_low_level_queue(mob)
            unilib.pkg.mtb_order_autonomy.do_action(mob)
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

        elseif fields.btn_order_alight then

            unilib.pkg.mtb_fly_alight.do_action(mob, 0, "stand")
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

        elseif fields.btn_order_fly then

            unimobs.mobkit_api.clear_both_queues(mob)

            mob.status = unimobs.mobkit_api.add_mob_memory(mob, "status", nil)
            unilib.pkg.hqb_fly_take_off.add_to_queue(mob, 0)

            unimobs.mobkit_api.do_entity_sound(mob, "misc")

            core.after(2.5, function()

                if unimobs.mobkit_api.is_object_alive(mob) then

                    unimobs.mobkit_api.clear_low_level_queue(mob)
                    mob.object:set_acceleration({x = 0, y = 0, z = 0})
                    mob.object:set_velocity({x = 0, y = 0, z = 0})

                end

            end, mob)

        elseif fields.btn_order_perch then

            -- N.B. In original code, multiple birds could be placed on the left shoulder (but none
            --      on the right shoulder)
            -- In unimobs, both shoulders are available (one is chosen at random if both are
            --      unoccupied), and only one bird per shoulder is allowed

            if shoulder_table[pname] == "both" then
                return false
            end

            unilib.pkg.mtb_order_stand_here.do_action(mob)
            unimobs.mobkit_api.do_entity_animation(mob, "stand")
            unimobs.mobkit_api.do_entity_sound(mob, "misc")

            -- Use the free shoulder or, if both are free, choose one at random
            local shoulder_pos
            if not shoulder_table[pname] then

                if random(2) == 1 then

                    shoulder_pos = mob.perch_left_offset or {x = 0.5, y = -6.0, z = 0}
                    mob.object:set_attach(player, "Arm_Left", shoulder_pos, {x = 0, y = 0, z = 180})
                    shoulder_table[pname] = "left"

                else

                    shoulder_pos = mob.perch_right_offset or {x = -0.5, y = -6.0, z = 0}
                    mob.object:set_attach(
                        player, "Arm_Right", shoulder_pos, {x = 0, y = 0, z = 180}
                    )
                    shoulder_table[pname] = "right"

                end


            elseif shoulder_table[pname] == "left" then

                shoulder_pos = mob.perch_right_offset or {x = -0.5, y = -6.0, z = 0}
                mob.object:set_attach(player, "Arm_Right", shoulder_pos, {x = 0, y = 0, z = 180})
                shoulder_table[pname] = "both"

            else

                shoulder_pos = mob.perch_left_offset or {x = 0.5, y = -6.0, z = 0}
                mob.object:set_attach(player, "Arm_Left", shoulder_pos, {x = 0, y = 0, z = 180})
                shoulder_table[pname] = "left"

            end

            mob.object:set_properties({physical = false})

            core.after(unimobs.petz_setting.detach_from_shoulder_interval, function()

                if unimobs.mobkit_api.is_object_alive(mob) then

                    mob.object:set_detach()
                    mob.object:set_properties({physical = true})

                    -- N.B. After being detached, parrots and toucans are partially beneath the
                    --      surface; correct for that (see the "mob_parrot_normal" package for some
                    --      similar corrective code)

                    -- Add 0.5 to the x and z coordinates to make sure the bird re-appears to the
                    --      player's side, not under their feet (using a random sign, because the
                    --      player might be facing in any direction)
                    local x_offset = 0.5
                    if random(2) == 1 then
                        x_offset = -0.5
                    end

                    local z_offset = 0.5
                    if random(2) == 1 then
                        z_offset = -0.5
                    end

                    local bird_pos = mob.object:get_pos()
                    mob.object:set_pos({
                        x = bird_pos.x + x_offset,
                        y = ceil(bird_pos.y),
                        z = bird_pos.z + z_offset,
                    })

                end

            end, mob)

        -- Action buttons
        elseif fields.btn_muted then

            if not mob.is_muted_flag then
                mob.is_muted_flag = unimobs.mobkit_api.add_mob_memory(mob, "is_muted_flag", true)
            else
                mob.is_muted_flag = unimobs.mobkit_api.add_mob_memory(mob, "is_muted_flag", false)
            end

            reopen_formspec_flag = true

        elseif fields.btn_show_nametag then

            if not mob.show_nametag_flag then

                mob.show_nametag_flag =
                    unimobs.mobkit_api.add_mob_memory(mob, "show_nametag_flag", true)

            else

                mob.show_nametag_flag =
                    unimobs.mobkit_api.add_mob_memory(mob, "show_nametag_flag", false)

            end

            reopen_formspec_flag = true

        elseif fields.btn_genetics then

            core.show_formspec(
                pname,
                "unilib:form_unimobs_show_mob_genetics",
                unimobs.petz_api.create_show_mob_genetics_form(mob)
            )

        elseif fields.btn_abandon then

            core.show_formspec(
                pname,
                "unilib:form_unimobs_confirm_abandon_mob",
                create_confirm_abandon_mob_form()
            )

        elseif fields.btn_dreamcatcher then

            unilib.pkg.item_dreamcatcher_pet.drop_from_mob(mob)

        elseif fields.btn_set_home then

            mob.back_home_pos =
                    unimobs.mobkit_api.add_mob_memory(mob, "back_home_pos", mob.object:get_pos())
            reopen_formspec_flag = true

        elseif fields.btn_auto_home then

            if not mob.back_home_flag then
                mob.back_home_flag = unimobs.mobkit_api.add_mob_memory(mob, "back_home_flag", true)
            else
                mob.back_home_flag = unimobs.mobkit_api.add_mob_memory(mob, "back_home_flag", false)
            end

            reopen_formspec_flag = true

        elseif fields.btn_herding then

            if not mob.is_herding_flag then

                mob.is_herding_flag =
                        unimobs.mobkit_api.add_mob_memory(mob, "is_herding_flag", true)

            else

                mob.is_herding_flag =
                        unimobs.mobkit_api.add_mob_memory(mob, "is_herding_flag", false)

            end

            reopen_formspec_flag = true

        elseif fields.btn_saddlebag then

            core.show_formspec(
                pname, "unilib:form_unimobs_saddlebag", create_saddlebag_form(pname, mob)
            )

        elseif fields.btn_trade then

            core.show_formspec(
                pname, "unilib:form_unimobs_sell_mob", create_sell_mob_form(mob)
            )

        -- Entry boxes
        elseif fields.nametag_entry and fields.nametag_entry ~= mob.nametag then

            mob.nametag = unimobs.mobkit_api.add_mob_memory(
                mob, "nametag", F(string.sub(fields.nametag_entry, 1, max_name_length))
            )

        -- Extension buttons
        elseif extension_table[mob.mob_type] then

            -- Check every extension button for this mob
            for _, mini_table in ipairs(extension_table[mob.mob_type]) do

                if fields["btn_extension_" .. mini_table.id] then

                    -- Button was clicked, so call the button's callback
                    if mini_table.click_func then

                        mini_table.click_func(mob)

                        -- Should the formspec be reopened?
                        if mini_table.draw_func then

                            draw_table = mini_table.draw_func(mob)
                            if draw_table.reopen_flag then
                                reopen_formspec_flag = true
                            end

                        end

                        if mini_table.order_flag then
                            unimobs.mobkit_api.do_entity_sound(mob, "misc")
                        end

                        -- Having found the data for the extension button, don't check the rest
                        --      of "extension_table"
                        break

                    end

                end

            end

        end

        unimobs.petz_api.update_mob_nametag(mob)

        if reopen_formspec_flag then
            core.show_formspec(pname, formname, unimobs.petz_api.create_standard_mob_form(pname))
        end

        return true

    else

        return false

    end

end)

