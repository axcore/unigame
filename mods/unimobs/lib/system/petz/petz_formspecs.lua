local function get_header_str(pname, mob, middle_height)

    -- (The header is immovable)
    local x = 0.5
    local y = 0
    local spawnegg_img = "unilib_spawnegg_" .. mob.mob_type .. ".png"

    local header_str = "box[" .. x .. "," .. y .. ";0.85,1;" .. dark_bg_colour .. "]" ..
        "image[" .. (x + 0.025) .. "," .. (y + 0.075) .. med_size_str .. spawnegg_img .. "]"

    if mob.is_pet_flag then

        local name_msg = FS("Name")
        if core.check_player_privs(pname, "unilib_admin") and mob._id then
            name_msg = name_msg .. " (ID #" .. mob._id .. ")"
        end

        header_str = header_str ..
            "field[" .. (x + med_x_offset + 0.25) .. "," .. (y + 0.5) .. ";3,1;nametag_entry;" ..
                name_msg .. ":" .. ";" .. mob.nametag .. "]"

    end

    x = 4.9
    y = 0.1
    if mob.is_male_flag then

        header_str = header_str ..
            "image[" .. x .. "," .. y .. med_size_str .. "unilib_gui_petz_male.png]" ..
            "tooltip[" .. x .. "," .. y .. med_size_str .. FS("Gender") .. "]" ..
            "label[" .. (x + sml_x_offset) .. "," .. (y + med_y_offset) .. ";" .. FS("Male") .. "]"

    else

        header_str = header_str ..
            "image[" .. x .. "," .. y .. med_size_str .. "unilib_gui_petz_female.png]" ..
            "tooltip[" .. x .. "," .. y .. med_size_str .. FS("Gender") .. "]" ..
            "label[" .. (x + sml_x_offset) .. "," .. (y + med_y_offset) .. ";" ..
                FS("Female") .. "]"

    end

    x = 7.4
    y = 0.1
    if not mob.is_baby_flag then

        header_str = header_str ..
            "image[" .. x .. "," .. y .. med_size_str .. "unilib_gui_petz_adult.png]" ..
            "tooltip[" .. x .. "," .. y .. med_size_str .. FS("Growth stage") .. "]" ..
            "label[" .. (x + sml_x_offset) .. "," .. (y + med_y_offset) .. ";" .. FS("Adult") .. "]"

    elseif not unimobs.petz_setting.show_formspec_time_flag then

        header_str = header_str ..
            "image[" .. x .. "," .. y .. med_size_str .. "unilib_gui_petz_baby.png]" ..
            "tooltip[" .. x .. "," .. y .. med_size_str .. FS("Growth stage") .. "]" ..
            "label[" .. (x + sml_x_offset) .. "," .. (y + med_y_offset) .. ";" .. FS("Baby") .. "]"

    else

        local remain_time = unimobs.kitz_api.round_number(
            mob.baby_growth_max_time - mob.baby_growth_time
        )

        x = 6.9

        header_str = header_str ..
            "image[" .. x .. "," .. y .. med_size_str .. "unilib_gui_petz_baby.png]" ..
            "tooltip[" .. x .. "," .. y .. med_size_str .. FS("Growth stage") .. "]" ..
            "label[" .. (x + sml_x_offset) .. "," .. (y + med_y_offset) .. ";" .. FS("Baby") ..
                " (" .. format_time(remain_time) .. ")]"

    end

    -- (Darker background for the middle section, if it contains any rows)
    if middle_height > 0 then

        header_str = header_str ..
            "box[0.5,1.25;" .. (formspec_width - 1.25) .. "," .. (middle_height + 0.35) .. ";" ..
                dark_bg_colour .. "]"

    end

    return header_str

end

