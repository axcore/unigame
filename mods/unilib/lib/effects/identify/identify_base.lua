local S = unilib.intllib

-- Table of players and the data used to handle item identification, in the form
--      identify_status_table[pname] = {enabled_flag = BOOL, pointed_thing = STRING}
local identify_status_table = {}

-- Can't draw an inventory cube from these .drawtypes
local drawtype_exclude_table = {
    fencelike = true,
    firelike = true,
    plantlike = true,
    plantlike_rooted = true,
    raillike = true,
    signlike = true,
    torchlike = true,
}

-- Standard label colours
local colour_red = 0xff3c0a
local colour_white = 0xffffff
local colour_yellow = 0xd0c526

-- Default image scale for nodes
local img_scale_node = 0.3
-- Default image scale for craftitems, assuming a 16x16 texture
-- N.B. 2.5 in original code; the new value is simpler to scale for 32x32, 48x48 etc
local img_scale_craftitem = 2.4

-- Flags set to true, when code in ../lib/effects/announce/announced_base.lua reports that a "long"
--      annoucement is visible (meaning that the "short" announcements generated by code in this
--      file will be ignored); the key-value pair is removed when the same code reports that no
--      "long" announcement is visible
-- Table in the form
--      long_announce_table[pname] = true
local long_announce_table = {}
-- Flags set to true, when the value of "long_announce_flag" is switched from true to false, meaning
--      that we should send an identify announcement (normally, they aren't sent unless the player
--      points at something new); the key-value pair is removed when we send an identify
--      announcement (or decide not to send one)
-- Table in the form
--      resume_identify_table[pname] = true
local resume_identify_table = {}

---------------------------------------------------------------------------------------------------
-- Local functions - setup
---------------------------------------------------------------------------------------------------

local function enable_identify_for_player(pname)

    identify_status_table[pname]["enabled_flag"] = true

end

local function disable_identify_for_player(pname)

    identify_status_table[pname]["enabled_flag"] = false

end

local function initialise_player_data(pname)

    identify_status_table[pname] = {
        enabled_flag = false,
        pointed_thing = "ignore",
    }

    -- Item identification is not necessarily visible on connection
    local player = core.get_player_by_name(pname)
    if unilib.utils.get_player_attribute(player, "identify_enabled") == "true" then
        enable_identify_for_player(pname)
    end

end

