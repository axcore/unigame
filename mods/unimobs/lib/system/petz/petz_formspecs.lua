function unimobs.petz_api.create_show_mob_genetics_form(mob)

    -- Original to unimobs
    -- Creates the formspec for displaying genetic data
    -- N.B. This function is a stripped-down version of the code found in the
    --      "device_analyser_dna" package

    -- Compile a table of descriptions ("gene_name") matching each "gene_type" for this mob
    -- When no description is available, that gene is not supposed to be visible
    local convert_table = {}
    local gene_count = 0

    local data_table = unimobs.petz_global.mob_table[mob.mob_type]
    if data_table ~= nil then

        for _, mini_list in ipairs(data_table.genetic_init_list) do

            -- mini_list in the form { gene_type, gene_name, ... }
            if mini_list[2] ~= nil and mini_list[2] ~= "" then

                convert_table[mini_list[1]] = mini_list[2]
                gene_count = gene_count + 1

            end

        end

    end

    -- Compose the formspec
    local formspec = "size[6," .. ((gene_count / 2) + 1) .. ";]" ..
            "box[0,0;0.7,0.8;" .. dark_bg_colour .. "]" ..
            "image[0.025,0.05;0.8,0.8;unilib_spawnegg_" .. mob.mob_type .. ".png]" ..
            "label[1,0.2;" .. FS("Genetic traits") .. "]"

    -- Show genetic traits in alphabetical order of their description ("gene_name"), not by
    --      alphabetical order of their types ("gene_type")
    for i, gene_type in ipairs(unimobs.mobkit_api.sort_keys_by_values(convert_table)) do

        local genetic_value = mob.genetic_table[gene_type]
        if genetic_value ~= nil then

            local msg
            local y_offset = (i * 0.5) + 0.5
            local range_table = data_table.genetic_range_table[gene_type]
            if range_table == nil then

                msg = genetic_value

            else

                msg = genetic_value .. "/" .. range_table.overall_max

                -- Show award ribbons, when earned
                ratio = genetic_value / range_table.overall_max
                if ratio == 1 then
                    img = "unilib_gui_petz_award_gold.png"
                elseif ratio >= 0.75 then
                    img = "unilib_gui_petz_award_silver.png"
                elseif ratio >= 0.5 then
                    img = "unilib_gui_petz_award_bronze.png"
                else
                    img = "unilib_gui_petz_award_none.png"
                end

                formspec = formspec .. "image[0.15," .. y_offset .. ";0.5,0.5;" .. img .. "]"

            end

            formspec = formspec ..
                "label[1," .. y_offset .. ";" .. string.format("%-8s", msg) .. " " ..
                    F(convert_table[gene_type]) .. "]"

        end

    end

    return formspec

end

