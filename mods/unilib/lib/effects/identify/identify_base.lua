function unilib.identify.toggle_mode(pname)

    -- Called from the chat command /what
    -- Enables or disables the HUD for identifying pointed nodes

    local player = core.get_player_by_name(pname)

    if identify_status_table[pname]["enabled_flag"] then

        -- Disable
        unilib.utils.set_player_attribute(player, "identify_enabled", "")
        disable_identify_for_player(pname)
        cancel_announcement(pname)

        -- (When the HUD is only visible after punching, then confirm the change in the chat window;
        --      otherwise, don't bother)
        if unilib.setting.announce_optimise_flag then
            return S("Identification HUD disabled, punch an item to identify it")
        end

    else

        -- Enable
        unilib.utils.set_player_attribute(player, "identify_enabled", "true")
        enable_identify_for_player(pname)

        if unilib.setting.announce_optimise_flag then
            return S("Identification HUD enabled")
        end

    end

end

