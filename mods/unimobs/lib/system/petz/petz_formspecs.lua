local function create_saddlebag_inventory(pname)

    -- Was petz.create_detached_saddlebag_inventory()
    -- Creates a detached inventory for the saddle-bag, one for each player (but only when needed)
    -- N.B. The original code created a single inventory for all players; that bug is fixed here

    local inv = core.create_detached_inventory("item_saddlebag_normal_" .. pname, {

        allow_move = function(inv, from_list, from_index, to_list, to_index, count, player)

            -- N.B. These log messages resemble the ones used by
            --      unilib.utils.set_inventory_action_loggers()
            unilib.utils.log_player_action(player, "moves items in saddle-bag")
            local stack = inv:get_stack(from_list, from_index)
            return stack:get_count()

        end,

        allow_put = function(inv, listname, index, stack, player)

            unilib.utils.log_player_action(
                player, "moves", stack:get_name(), stack:get_count(), "to saddle-bag"
            )

            return stack:get_count()

        end,

        allow_take = function(inv, listname, index, stack, player)

            unilib.utils.log_player_action(
                player, "moves", stack:get_name(), stack:get_count(), "from saddle-bag"
            )

            return stack:get_count()

        end,
    })

    -- Size and width of saddle-bag inventory
    inv:set_size("saddlebag", saddlebag_inv_size)
    inv:set_width("saddlebag", saddlebag_inv_width)

    return inv

end

local function get_saddlebag_inventory(pname)

    -- Original to unimobs

    local inv = core.get_inventory({type = "detached", name = "item_saddlebag_normal_" .. pname})
    if inv then
        return inv
    else
        return create_saddlebag_inventory(pname)
    end

end

