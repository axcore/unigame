core.register_on_joinplayer(function(player)

    -- N.B. Prior to v1.2.0, this code stored a number of player attributes, which have since been
    --      refactored (only the "identify_enabled" flag remains)
    if unilib.utils.get_player_attribute(player, "identify_pointed_thing") ~= "" then

        -- Remove the obsolete attributes
        unilib.utils.set_player_attribute(player, "identify_background_left", nil)
        unilib.utils.set_player_attribute(player, "identify_background_middle", nil)
        unilib.utils.set_player_attribute(player, "identify_background_right", nil)
        unilib.utils.set_player_attribute(player, "identify_image", nil)
        unilib.utils.set_player_attribute(player, "identify_name", nil)
        unilib.utils.set_player_attribute(player, "identify_mod", nil)
        unilib.utils.set_player_attribute(player, "identify_pointed_thing", nil)
        unilib.utils.set_player_attribute(player, "identify_item_type_in_pointer", nil)

    end

    -- Now proceed with normal initialisation
    initialise_player_data(player:get_player_name())

end)

core.register_on_leaveplayer(function(player)
    identify_status_table[player:get_player_name()] = nil
end)

if not unilib.setting.announce_optimise_flag then

    -- Non-optimised code, from "what_is_this_uwu" mod - identify the node at which the player is
    --      pointing
    do_simple_loop()

else

    -- Code optimised for servers, from "what_is_this_owo" mod - identify a node when the player
    --      punches it, cancel the announcement when the player "punches" something else (e.g.
    --      another player, an entity, the air)
    do_optimised_loop()

end
