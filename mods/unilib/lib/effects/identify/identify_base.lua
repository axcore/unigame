-- Local functions - announcement support functions
---------------------------------------------------------------------------------------------------

local function generate_inventorycube(img1, img2, img3)

    if not img1 then
        return ""
    end

    img2 = img2 or img1
    img3 = img3 or img1

    img1 = img1 .. "^[resize:16x16"
    img2 = img2 .. "^[resize:16x16"
    img3 = img3 .. "^[resize:16x16"

    return "[inventorycube" ..
        "{" .. img1:gsub("%^","&") ..
        "{" .. img2:gsub("%^","&") ..
        "{" .. img3:gsub("%^","&")

end

local function generate_node_data(full_name)

    -- Returns a list of three items:
    --      - A formspec portion with a single inventorycube[] element, used to show the specified
    --          item in an isometric view (or "ignore" on failure)
    --      - A string identifying the pointed item, either "node" or "craftitem"
    --      - The item's definition table on success (or "false" on failure)

    local node_def_table = core.registered_nodes[full_name]
    local orig_def_table = node_def_table
    if not orig_def_table then
        return "ignore", "node", false
    end

    if not unilib.setting.announce_optimise_flag then

        -- Non-optimised code, from "what_is_this_uwu" mod

        if node_def_table.groups["not_in_creative_inventory"] then

            local drop = node_def_table.drop
            -- N.B. Fix for original code, which shows an "Unknown object" for any node which has
            --      drop = ""
--          if drop and type(drop) == "string" then
            if drop and type(drop) == "string" and drop ~= "" then

                full_name = drop
                node_def_table = core.registered_nodes[drop]
                if not node_def_table then
                    node_def_table = core.registered_craftitems[drop]
                end

            end

        end

        if not node_def_table or
                (not node_def_table.tiles and not node_def_table.inventory_image) then
            return "ignore", "node", false
        end

        local tiles = node_def_table.tiles
        local mod_name, item_name = unilib.utils.split_name(full_name)

        if node_def_table.inventory_image:sub(1, 14) == "[inventorycube" then

            return node_def_table.inventory_image .. "^[resize:146x146", "node", orig_def_table

        elseif node_def_table.inventory_image ~= "" then

            return node_def_table.inventory_image .. "^[resize:16x16", "craftitem", orig_def_table

        else

            -- N.B. Fix for original code. When plantlike (etc) nodes are to be displayed and they
            --      don't have an .inventory_image, then the inventorycube drawn looks weird.
            --      Instead, just use the first image in .tiles, as if it were the inventory image
            --[[
            if not tiles[1] then
                return "", "node", orig_def_table
            end
            ]]--
            if not tiles[1] then

                return "", "node", orig_def_table

            elseif drawtype_exclude_table[node_def_table.drawtype] then

                if type(tiles[1]) == "table" then
                    return tiles[1].name .. "^[resize:128x128", "node", orig_def_table
                else
                    return tiles[1] .. "^[resize:128x128", "node", orig_def_table
                end

            end

            tiles[3] = tiles[3] or tiles[1]
            tiles[6] = tiles[6] or tiles[3]

            if type(tiles[1]) == "table" then
                tiles[1] = tiles[1].name
            end

            if type(tiles[3]) == "table" then
                tiles[3] = tiles[3].name
            end

            if type(tiles[6]) == "table" then
                tiles[6] = tiles[6].name
            end

            return generate_inventorycube(tiles[1], tiles[6], tiles[3]), "node", orig_def_table

        end

    else

        -- Code optimised for servers, from "what_is_this_owo" mod

        local tiles = node_def_table.tiles
        local mod_name, item_name = unilib.utils.split_name(full_name)

        if node_def_table.inventory_image:sub(1, 14) == "[inventorycube" then

            return node_def_table.inventory_image .. "^[resize:146x146", "node", orig_def_table

        elseif node_def_table.inventory_image ~= "" then

            return node_def_table.inventory_image.."^[resize:16x16", "craftitem", orig_def_table

        elseif item_name:sub(-2) == "_a" or
                item_name:sub(-2) == "_b" or
                item_name:sub(-2) == "_c" then

            local temp = mod_name .. ":" .. item_name:sub(1, -3)
            local tile_temp = core.registered_craftitems[temp].inventory_image

            return tile_temp .. "^[resize:16x16", "craftitem", orig_def_table

        else

            --[[
            if not tiles[1] then
                return "", "node", orig_def_table
            end
            ]]--
            if not tiles[1] then

                return "", "node", orig_def_table

            elseif drawtype_exclude_table[node_def_table.drawtype] then

                if type(tiles[1]) == "table" then
                    return tiles[1].name .. "^[resize:128x128", "node", orig_def_table
                else
                    return tiles[1] .. "^[resize:128x128", "node", orig_def_table
                end

            end

            if not tiles[3] then
                tiles[3] = tiles[1]
            end

            if not tiles[6] then
                tiles[6] = tiles[3]
            end

            if type(tiles[1]) == "table" then
                tiles[1] = tiles[1].name
            end

            if type(tiles[3]) == "table" then
                tiles[3] = tiles[3].name
            end

            if type(tiles[6]) == "table" then
                tiles[6] = tiles[6].name
            end

            return generate_inventorycube(tiles[1], tiles[6], tiles[3]), "node", orig_def_table

        end

    end

end

