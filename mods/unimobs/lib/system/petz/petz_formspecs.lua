local function buy_mob(mob, buyer)

    -- From petz.buy()
    -- Transfers ownership of the mob to the specified "buyer"

    local buyer_name = buyer:get_player_name()
    local inv_buyer = buyer:get_inventory()
    if not mob.owner then
        return
    end

    local seller = core.get_player_by_name(mob.owner)
    local item_index = mob.trade_item_index
    local item_amount = mob.trade_item_amount
    -- N.B. Code in petz_settings.lua has already checked that the item exists
    local full_name = unimobs.petz_setting.trade_item_list[item_index]
    local item_def_table = core.registered_items[full_name]
    local item_stack = ItemStack({name = full_name, count = item_amount})

    if not seller then

        core.chat_send_player(buyer_name, S("The seller is not online"))
        return

    elseif not inv_buyer:contains_item("main", item_stack) then

        core.chat_send_player(
            buyer_name,
            S(
                "You don't have enough to buy this creature! (@1 x @2)",
                item_def_table.description,
                tostring(item_amount)
            )
        )

        return

    end

    -- Make the purchase
    inv_buyer:remove_item("main", item_stack)
    local inv_seller = seller:get_inventory()
    if inv_seller:room_for_item("main", item_stack) then

        inv_seller:add_item("main", item_stack)

    else

        local seller_pos = seller:get_pos()
        core.item_drop(item_stack, seller, seller_pos)

    end

    if mob.is_mountable_flag and mob.driver then
        unimobs.petz_api.force_dismount_player_from_mob(mob.driver)
    end

    if not mob.nametag or mob.nametag == "" then

        unimobs.petz_api.abandon_tamed_mob(
            mob,
            unilib.utils.capitalise_translation(
                S(
                    "You have sold your @1 to @2",
                    unimobs.petz_api.get_insertion(mob.mob_type, "object"),
                    buyer_name
                )
            )
        )

    else

        unimobs.petz_api.abandon_tamed_mob(
            mob,
            unilib.utils.capitalise_translation(
                S(
                    "You have sold your @1, @2, to @3",
                    unimobs.petz_api.get_insertion(mob.mob_type, "object"),
                    mob.nametag,
                    buyer_name
                )
            )
        )

    end

    unimobs.kitz_api.set_mob_owner(mob, buyer_name)
    core.chat_send_player(
        buyer_name,
        unilib.utils.capitalise_translation(
            S(
                "Congratulations, you've bought @1!",
                unimobs.petz_api.get_insertion(mob.mob_type, "object_an")
            )
        )
    )

end

