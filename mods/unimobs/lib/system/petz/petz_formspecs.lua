local function get_lists_of_extension_buttons(mob)

    -- Original to unimobs
    -- Returns two lists, each containing mini-tables from "extension_table" for the specified "mob"
    -- (Either list may be empty)

    local order_ext_btn_list = {}
    local action_ext_btn_list = {}

    if mob.is_pet_flag and extension_table[mob.mob_type] then

        for _, mini_table in ipairs(extension_table[mob.mob_type]) do

            if mini_table.order_flag and
                    mob.obeys_orders_flag and
                    mob.has_tamagotchi_mode_flag and (
                        unimobs.petz_setting.enable_tamagotchi_mode_flag or
                        unimobs.petz_setting.force_formspec_orders_flag
                    ) then
                table.insert(order_ext_btn_list, mini_table)
            elseif not mini_table.order_flag then
                table.insert(action_ext_btn_list, mini_table)
            end

        end

    end

    return order_ext_btn_list, action_ext_btn_list

end

local function draw_extension_button(btn_str, mob, x, y, gap, btn_count, mini_table)

    -- Original to unimobs
    -- Draws an extension button at the specified position

    -- Get a table of parameters, telling us how to draw the button
    local draw_table = {}
    if mini_table.draw_func then
        draw_table = mini_table.draw_func(mob)
    end

    local this_str = ""
    if not draw_table.reopen_flag then
        this_str = "image_button_exit"
    else
        this_str = "image_button"
    end

    this_str = this_str .. "[" .. (x + gap + btn_count) .. "," .. y .. med_size_str

    if draw_table.img then
        this_str = this_str .. draw_table.img
    else
        this_str = this_str .. "unilib_gui_petz_order_follow.png"
    end

    this_str = this_str .. ";btn_extension_" .. tostring(mini_table.id) .. ";"
    if draw_table.text then
        this_str = this_str .. draw_table.text
    end

    this_str = this_str .. "]"

    if draw_table.tooltip and draw_table.tooltip ~= "" then

        this_str = this_str .. "tooltip[" .. (x + gap + btn_count) .. "," .. y .. med_size_str ..
                F(draw_table.tooltip) .. "]"

    end

    return btn_str .. this_str

end

local function get_genetic_description(mob, data_table)

    -- Original to unimobs
    -- Get an average of the mob's genetic values, and use it to generate a one-line description
    -- Note that the average includes non-ranged values and all "hidden" genetic traits

    -- The ."genetic_init_list" field contains values such as the mob's skin colour, which we don't
    --      need to include
    local check_table = {}
    -- mini_list in the form { gene_type, gene_name, ... }
    for _, mini_list in ipairs(data_table.genetic_init_list) do
        check_table[mini_list[1]] = true
    end

    -- Generate a combined average of the mob's genetic traits (a value in the range 0-1)
    local total = 0
    local count = 0
    for gene_type, genetic_value in pairs(mob.genetic_table) do

        if check_table[gene_type] then

            local range_table = data_table.genetic_range_table[gene_type]
            if range_table then

                total = total + (
                    (genetic_value - range_table.overall_min) /
                    (range_table.overall_max - range_table.overall_min)
                )

            else

                -- If not a continuous "range" of values (e.g. 0-10), just assume a fixed value
                total = total + 0.5

            end

            count = count + 1

        end

    end

    local average
    if count > 0 then
        average = total / count
    end

    -- Convert the average into a description
    if average <= 0 then
        return genetic_descrip_list[0]
    elseif average >= 1 then
        return genetic_descrip_list[#genetic_descrip_list]
    else
        return genetic_descrip_list[floor((average * #genetic_descrip_list) + 0.5)]
    end

end

local function compile_discoverable_item_list(first_name, item_table)

    -- Called by get_feed_str(), etc
    -- The items used (for example) to feed a mob, are stored in unimobs.petz_msetting, having been
    --      populated from the remix CSV
    -- Two items of data, already retrieved from unimobs.petz_msetting, are passed to this function
    --      as arguments. "item_table" is a table whose keys are the names of nodes, craftitems etc
    --      (e.g. "unilib:crop_wheat_harvest"), and "first_name" is the name of the node, craftitem
    --      etc that was the first specified by the remix CSV
    --
    -- Returns the table converted to a list in a predictable order, namely
    --      { first_name, all_other_items_in_alphabetical_order)

    local return_list = {}
    for key, _ in pairs(item_table) do

        if key ~= first_name then
            table.insert(return_list, key)
        end

    end

    table.sort(return_list)
    table.insert(return_list, 1, first_name)

    return return_list

end

