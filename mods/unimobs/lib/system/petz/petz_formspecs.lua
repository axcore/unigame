local function format_time(seconds)

    -- Original to unimobs
    -- Converts an integer value, a number in seconds, into a string in the form M:SS

    local minutes = floor(seconds / 60)
    local secs = seconds % 60
    return string.format("%d:%02d", minutes, secs)

end

local function get_item_description(full_name)

    -- Original to unimobs
    -- Gets a description of the specified item, removing additional lines, and reducing the length
    --      of very long lines
    -- Special case: use a mob's description, rather than the corresponding spawnegg description
    -- If no description is available, returns the item's .name. If "full_name" is a group name
    --      like "group:stick", returns it unmodified. If the item "full_name" doesn't exist,
    --      returns the string "n/a"

    local def_table
    if full_name and full_name ~= "" then
        def_table = core.registered_items[full_name]
    end

    if def_table then

        if def_table.groups and def_table.groups.spawnegg and def_table.mob_type then

            -- Special case: don't display the spawnegg's description, but the mob's description
            return unilib.utils.contract_long_lines(
                unimobs.petz_global.mob_table[def_table.mob_type]["description"]
            )

        elseif def_table.description then

            return unilib.utils.contract_long_lines(
                unilib.utils.get_first_line(def_table.description), max_description_length
            )

        else

            return unilib.utils.contract_long_lines(def_table.name, max_description_length)

        end

    elseif full_name ~= nil and string.sub(full_name, 1, 6) == "group:" then

        return full_name

    else

        return "n/a"

    end

end

local function get_row_counts(mob, show_repel_flag)

    -- Original to unimobs
    -- Returns two integers, representing the number of rows that need to be drawn in the middle
    --      section of the formspec

    local left_count = 0
    -- get_owner_str()
    if mob.owner and (mob.for_sale_flag or not core.is_singleplayer()) then
        left_count = left_count + 1
    end
    -- get_mob_type_str(), get_mob_skin_str()
    left_count = left_count + 2
    -- get_follow_str(), get_feed_str(), get_breed_str()
    if unimobs.petz_setting.show_formspec_items_flag then

        left_count = left_count + 3

        -- get_repel_str()
        if show_repel_flag then
            left_count = left_count + 1
        end

        -- get_capture_str()
        if mob.capture_type == "lasso" or
                mob.capture_type == "animal_net" or
                mob.capture_type == "bug_net" then
            left_count = left_count + 1
        end

    end

    -- get_health_str(), get_mating_str(), get_generation_str(), get_genetics_str()
    local right_count = 4
    -- get_tamagotchi_hunger_str(), get_tamagotchi_groom_str()
    if unimobs.petz_setting.enable_tamagotchi_mode_flag and mob.has_tamagotchi_mode_flag then
        right_count = right_count + 2
    end
    -- get_home_str()
    if mob.has_dreamcatcher_flag and mob.back_home_pos then
        right_count = right_count + 1
    end

    return left_count, right_count

end

