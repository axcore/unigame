    -- Adadpted from corresponding callback in original code

    if formname ~= "unilib:form_unimobs_saddlebag" then
        return false
    end

    -- Save the saddle-bag contents
    local pname = player:get_player_name()
    local mob = unimobs.petz_global.formspec_player_table[pname]
    if mob and mob.object then

        local inv = get_saddlebag_inventory(pname)
        local itemstacks_table = {}

        local inv_size = inv:get_size("saddlebag")
        if inv_size > 0 then

            for i = 1, inv_size do
                itemstacks_table[i] = inv:get_stack("saddlebag", i):to_table()
            end

            mob.saddlebag_inventory = itemstacks_table
            unimobs.mobkit_api.add_mob_memory(mob, "saddlebag_inventory", itemstacks_table)

        end

    end

    return true

end)

core.register_on_player_receive_fields(function(player, formname, fields)

    -- Callback for the formspec created by create_sell_mob_form()
    -- Adadpted from corresponding callback in original code

    if formname ~= "unilib:form_unimobs_sell_mob" then
        return false
    end

    local reopen_formspec_flag = false

    local pname = player:get_player_name()
    local mob = unimobs.petz_global.formspec_player_table[pname]
    if mob and mob.object and not mob.is_dead_flag then

        if fields.btn_for_sale then

            if not mob.for_sale_flag then

                mob.for_sale_flag = unimobs.mobkit_api.add_mob_memory(mob, "for_sale_flag", true)

            else

                mob.for_sale_flag = unimobs.mobkit_api.add_mob_memory(mob, "for_sale_flag", false)
                -- Change from original code - when the "for sale" button is switched for a "not for
                --      sale" button, reset the mob's trade properties, which resets the list and
                --      entry box below
                mob.trade_item_index = unimobs.mobkit_api.add_mob_memory(mob, "trade_item_index", 1)
                mob.trade_item_amount =
                        unimobs.mobkit_api.add_mob_memory(mob, "trade_item_amount", 1)

            end

            reopen_formspec_flag = true

            -- N.B. The nametag changes, depending on whether the mob is for sale, or not
            unimobs.petz_api.update_mob_nametag(mob)

        elseif fields.trade_exchange_list or fields.trade_amount_entry then

            local event = core.explode_textlist_event(fields.trade_exchange_list)
            if event.type == "CHG" then

                mob.trade_item_index =
                        unimobs.mobkit_api.add_mob_memory(mob, "trade_item_index", event.index)

            end

            mob.trade_item_amount = unimobs.mobkit_api.add_mob_memory(
                mob,
                "trade_item_amount",
                unimobs.kitz_api.delimit_number(
                    tonumber(fields.trade_amount_entry),
                    {min = 1, max = unimobs.petz_setting.max_trade_items}
                ) or 1
            )

            -- N.B. Change from original code - when the player selects an item, or specifies an
            --      amount, change the "not for sale" button to a "for sale" button
            mob.for_sale_flag = unimobs.mobkit_api.add_mob_memory(mob, "for_sale_flag", true)
            reopen_formspec_flag = true

        end

        if reopen_formspec_flag then
            core.show_formspec(pname, formname, create_sell_mob_form(mob))
        end

        return true

    else

        return false

    end

end)

